# INV-2 discipline: this module never opens a source file directly
# =============================================================================


def _direct_open_call_lines(path: Path) -> list[int]:
    """Line numbers of direct `open(...)` or `os.open(...)` calls in `path`."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    hits = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if isinstance(func, ast.Name) and func.id == "open":
            hits.append(node.lineno)
        elif (
            isinstance(func, ast.Attribute)
            and func.attr == "open"
            and isinstance(func.value, ast.Name)
            and func.value.id == "os"
        ):
            hits.append(node.lineno)
    return hits


def test_normalize_module_never_opens_a_file_directly(tmp_path):
    """`palaver/extract/normalize.py` reads only through `read_complete_records`
    (in turn, `open_source_readonly`) — no bare `open()`/`os.open()` call.

    Mirrors `tests/test_invariants.py::test_adapters_route_every_read_through_the_chokepoint`'s
    detector for the same discipline applied outside `palaver/ingest/adapters/`.
    Positive control: the identical detector run against a poisoned module
    that does call `open()` directly finds it, proving the detector is live
    rather than vacuously clean.
    """
    assert NORMALIZE_MODULE_PATH.exists()
    assert _direct_open_call_lines(NORMALIZE_MODULE_PATH) == []

    poisoned = tmp_path / "poisoned_normalize.py"
    poisoned.write_text("def read_it(path):\n    with open(path) as f:\n        return f.read()\n")
    assert _direct_open_call_lines(poisoned) == [2]
