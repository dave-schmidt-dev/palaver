def _synthetic_session_records(min_raw_bytes: int) -> list[dict]:
    """Build corpus-shaped records (human ask, tool call, large tool output,
    agent summary) repeated until the JSONL encoding exceeds `min_raw_bytes`.

    Shaped after real session traffic: a short human/agent turn either side
    of a tool call whose output dominates the record's raw size — the same
    profile the spike measured 900 KB -> ~47 KB against. Nothing here is
    real corpus text; every string is templated and invented for this test.
    """
    tool_cycle = ("Bash", "Edit", "Grep")
    records: list[dict] = []
    raw_bytes = 0
    i = 0
    while raw_bytes < min_raw_bytes:
        tool = tool_cycle[i % len(tool_cycle)]
        if tool == "Bash":
            tool_input = {"command": (f"run_the_build_step --target service-{i}\n") * 60}
        elif tool == "Edit":
            tool_input = {
                "file_path": f"/repo/src/module_{i}.py",
                "old_string": "x" * 300,
                "new_string": "y" * 300,
            }
        else:
            tool_input = {"pattern": f"TODO_{i}"}

        unit = [
            _user_record(
                f"please look into issue number {i} and fix the underlying cause of the failure",
                session_id="fixture-synth",
            ),
            {
                "type": "assistant",
                "sessionId": "fixture-synth",
                "message": {
                    "role": "assistant",
                    "content": [
                        {"type": "thinking", "thinking": "reasoning about the fix in detail " * 80},
                        {"type": "tool_use", "id": f"tu-{i}", "name": tool, "input": tool_input},
                    ],
                },
            },
            _tool_result_record(
                is_error=False,
                content=(
                    f"build output line {i} with some detail about what happened during this step\n"
                )
                * 400,
                session_id="fixture-synth",
            ),
            _assistant_text_record(
                f"fixed issue {i}, the tests now pass and behavior matches the ticket "
                "description precisely",
                session_id="fixture-synth",
            ),
        ]
        for record in unit:
            raw_bytes += len(json.dumps(record)) + 1
        records.extend(unit)
        i += 1
    return records


def test_synthesized_900kb_input_normalizes_under_60kb(tmp_path):
    """A ~900 KB synthesized JSONL session normalizes to well under 60 KB.

    The input is built programmatically by `_synthetic_session_records`,
    never read from a committed blob, and written to a real file so this
    exercises `normalize_path`'s read path (`read_complete_records` /
    `open_source_readonly`), not just in-memory record handling.
    """
    records = _synthetic_session_records(900_000)
    path = tmp_path / "synthetic-session.jsonl"
    _write_jsonl(path, records)

    raw_size = path.stat().st_size
    assert raw_size >= 900_000  # the input really is ~900 KB, not a token gesture at it

    normalized = normalize_path(path)
    normalized_size = len(normalized.encode("utf-8"))

    assert normalized_size < 60_000
    # Not just "under the bound" by luck: the reduction is the point.
    assert normalized_size < raw_size / 10


