def test_system_record_uses_adapter_derived_kind_name():
    """A `system` record's rendered kind comes from the adapter's own subtype table.

    Asserts equality against `SYSTEM_SUBTYPE_KINDS` itself (imported, not
    restated), so this fails if the two ever drift instead of silently
    agreeing with a hand-copied duplicate. The unmapped-subtype case is the
    negative control: it must fall back to the generic `system` kind rather
    than crashing or inventing a name.
    """
    known = {
        "type": "system",
        "subtype": "compact_boundary",
        "sessionId": "fixture-synth",
        "content": "invented compaction note for this test",
    }
    unknown = {
        "type": "system",
        "subtype": "some_future_subtype_not_yet_classified",
        "sessionId": "fixture-synth",
        "content": "invented future-system note for this test",
    }

    output = normalize_records([known, unknown])

    expected_kind = SYSTEM_SUBTYPE_KINDS["compact_boundary"]
    known_lines = _lines_containing(output, "invented compaction note")
    assert len(known_lines) == 1
    assert f"SYSTEM({expected_kind}):" in known_lines[0]

    unknown_lines = _lines_containing(output, "invented future-system note")
    assert len(unknown_lines) == 1
    assert "SYSTEM(system):" in unknown_lines[0]


