# --- record builders (invented content only, INV-9) -------------------------


def _user_record(text: str, *, is_meta: bool = False, session_id: str = "fixture-synth") -> dict:
    return {
        "type": "user",
        "sessionId": session_id,
        "isMeta": is_meta,
        "message": {"role": "user", "content": [{"type": "text", "text": text}]},
    }


def _assistant_text_record(text: str, *, session_id: str = "fixture-synth") -> dict:
    return {
        "type": "assistant",
        "sessionId": session_id,
        "message": {"role": "assistant", "content": [{"type": "text", "text": text}]},
    }


def _tool_use_record(name: str, tool_input: dict, *, session_id: str = "fixture-synth") -> dict:
    return {
        "type": "assistant",
        "sessionId": session_id,
        "message": {
            "role": "assistant",
            "content": [{"type": "tool_use", "id": "tu-1", "name": name, "input": tool_input}],
        },
    }


def _tool_result_record(*, is_error: bool, content: str, session_id: str = "fixture-synth") -> dict:
    return {
        "type": "user",
        "sessionId": session_id,
        "isMeta": False,
        "message": {
            "role": "user",
            "content": [
                {
                    "type": "tool_result",
                    "tool_use_id": "tu-1",
                    "is_error": is_error,
                    "content": content,
                }
            ],
        },
    }


def _line(record: dict) -> bytes:
    return (json.dumps(record) + "\n").encode("utf-8")


def _write_jsonl(path: Path, items: list) -> None:
    """Write a JSONL fixture. A `bytes` item is written verbatim (corrupt lines)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"".join(item if isinstance(item, bytes) else _line(item) for item in items))


def _lines_containing(output: str, needle: str) -> list[str]:
    return [line for line in output.splitlines() if needle in line]


