def test_long_text_is_clipped_with_elision_marker():
    """Text over the per-block cap is truncated with an explicit `…[+N chars]` marker.

    Positive control: a short text on a sibling record in the same input is
    rendered in full, unmarked — proving the cap applies to long text
    specifically, not to every line regardless of length.
    """
    long_text = "y" * 5000
    short_text = "invented short reply for this test"
    records = [_assistant_text_record(long_text), _assistant_text_record(short_text)]

    output = normalize_records(records)

    assert "…[+" in output
    assert "chars]" in output
    assert short_text in output
    short_line = _lines_containing(output, short_text)[0]
    assert "…[+" not in short_line


