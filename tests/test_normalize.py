"""Tests for `palaver.extract.normalize` — JSONL to semantic turn stream.

Every fixture built inline here is invented for this test (INV-9): no real
`~/.claude/` session store is ever opened, globbed, or read, and no prose in
this module was copied, sampled, or paraphrased from a real agent session.
The one *committed* fixture this module reads,
`tests/fixtures/compaction-boundary.jsonl`, was produced sanitized by task
1.7 and is exactly the source of `tests/fixtures/golden/compaction-boundary.normalized.txt`
below — nothing in the golden file is prose this module introduced.

**Why `test_injected_content_is_tagged_as_injected` is named exactly that.**
It was renamed 2026-08-14 from `test_injected_content_is_not_tier_one`, which
is now INV-8's charter `gate_test` name and belongs to task 3.3
(`tests/test_extraction.py`), where a write boundary actually exists to
reject a tier. This module has no tier and rejects nothing; it classifies
and tags. Carrying the old name here would make the charter's rejection
property read as covered when nothing in this file checks it.
"""

