def test_golden_compaction_boundary_matches_committed_fixture():
    """`normalize_path` on the committed fixture reproduces the reviewed golden file byte-for-byte.

    The golden file was generated by this implementation and then read back
    line by line against the raw fixture records before being committed —
    see the task report for the per-line check. This test's job is only to
    catch drift afterward, not to establish correctness on its own.
    """
    assert COMPACTION_FIXTURE_PATH.exists()
    normalized = normalize_path(COMPACTION_FIXTURE_PATH)
    golden = GOLDEN_PATH.read_text(encoding="utf-8")
    assert normalized == golden


def test_golden_fixture_channel_tags_match_the_raw_records():
    """Independent re-derivation: each golden line's tag matches what the raw record says.

    Re-reads `compaction-boundary.jsonl` itself (not through the normalizer)
    and checks each `user` record's `isMeta`/text against the tag the golden
    file carries for it, so this does not just re-assert the normalizer
    agrees with itself.
    """
    raw_lines = [json.loads(line) for line in COMPACTION_FIXTURE_PATH.read_text().splitlines()]
    user_records = [r for r in raw_lines if r["type"] == "user"]
    assert len(user_records) == 2
    for record in user_records:
        assert record["isMeta"] is False  # both are genuinely human-authored
    golden_lines = GOLDEN_PATH.read_text(encoding="utf-8").splitlines()
    human_lines = _lines_containing("\n".join(golden_lines), "HUMAN:")
    assert len(human_lines) == 2
    assert _lines_containing("\n".join(golden_lines), "INJECTED:") == []


