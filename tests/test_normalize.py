def test_injected_content_is_tagged_as_injected():
    """An `isMeta: true` record's line carries the injected tag and no human tag,
    with a genuinely human-authored record in the same input carrying the human tag.

    The positive control is not a separate test: without the human-channel
    record in this same input, a normalizer that emits nothing at all (or
    that emits no `HUMAN:` line ever) would still pass "no human tag on the
    injected line" vacuously. Requiring the human line to appear rules that
    out.
    """
    records = [
        _user_record(
            "<system-reminder>invented harness reminder text for this test</system-reminder>",
            is_meta=True,
        ),
        _user_record("please summarize the invented ticket for this test"),
    ]

    output = normalize_records(records)

    injected_lines = _lines_containing(output, "invented harness reminder text")
    assert len(injected_lines) == 1
    assert "INJECTED:" in injected_lines[0]
    assert "HUMAN:" not in injected_lines[0]

    # Positive control: the human-authored record in the same input.
    human_lines = _lines_containing(output, "invented ticket")
    assert len(human_lines) == 1
    assert "HUMAN:" in human_lines[0]
    assert "INJECTED:" not in human_lines[0]


def test_injected_prefix_without_ismeta_is_tagged_as_injected():
    """INV-8's second signal: a non-`isMeta` record still tags injected by text prefix.

    `isMeta: false` deliberately, so `classify_channel` cannot short-circuit
    on the structural flag — this exercises the prefix-table branch
    specifically. Paired with the same positive control pattern as above.
    """
    records = [
        _user_record("<command-name>/invented-status</command-name>", is_meta=False),
        _user_record("please check the invented deploy for this test"),
    ]

    output = normalize_records(records)

    injected_lines = _lines_containing(output, "invented-status")
    assert len(injected_lines) == 1
    assert "INJECTED:" in injected_lines[0]
    assert "HUMAN:" not in injected_lines[0]

    human_lines = _lines_containing(output, "invented deploy")
    assert len(human_lines) == 1
    assert "HUMAN:" in human_lines[0]


