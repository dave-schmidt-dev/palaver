# Robustness: a corrupt line does not fail the whole normalization
# =============================================================================


def test_malformed_json_line_is_skipped_not_fatal(tmp_path, caplog):
    """A corrupt JSONL line is logged and skipped; every well-formed record around it still renders.

    Positive control: the good records before and after the corrupt line
    both appear in the output, so this proves the corrupt line was skipped
    in place rather than truncating the rest of the file.
    """
    path = tmp_path / "corrupt.jsonl"
    _write_jsonl(
        path,
        [
            _user_record("invented message before the corrupt line"),
            b"{not valid json at all\n",
            _user_record("invented message after the corrupt line"),
        ],
    )

    with caplog.at_level(logging.WARNING):
        output = normalize_path(path)

    assert "invented message before the corrupt line" in output
    assert "invented message after the corrupt line" in output
    assert any("Unparseable" in record.message for record in caplog.records)


