def test_tool_use_and_tool_result_carry_no_channel_tag():
    """Tool calls and tool outcomes are structural lines, never HUMAN/INJECTED/AGENT.

    A tool result is something that happened, not something said, so it has
    no channel; a `tool_use` block belongs to an `AGENT` record but is
    rendered on its own `tool>` line rather than folded into the `AGENT:`
    text line, so a reader (or a downstream quote-grounding gate) cannot
    mistake a rendered command for something the agent said in prose.
    """
    records = [
        _tool_use_record("Bash", {"command": "invented-command --for-this-test"}),
        _tool_result_record(is_error=False, content="invented tool output for this test"),
    ]

    output = normalize_records(records)

    tool_lines = _lines_containing(output, "invented-command")
    assert len(tool_lines) == 1
    assert "tool>" in tool_lines[0]
    for tag in ("HUMAN:", "INJECTED:", "AGENT:"):
        assert tag not in tool_lines[0]

    result_lines = _lines_containing(output, "invented tool output")
    assert len(result_lines) == 1
    assert "result>" in result_lines[0]
    for tag in ("HUMAN:", "INJECTED:", "AGENT:"):
        assert tag not in result_lines[0]


def test_tool_result_error_is_marked_distinctly_from_success():
    """`is_error: true` renders `result[error]>`; `is_error: false` renders plain `result>`.

    The success case is the positive control: without it, a normalizer that
    always emitted `result[error]>` regardless of `is_error` would still
    pass a lone "error is marked" assertion.
    """
    records = [
        _tool_result_record(is_error=True, content="invented failure output for this test"),
        _tool_result_record(is_error=False, content="invented success output for this test"),
    ]

    output = normalize_records(records)

    error_lines = _lines_containing(output, "invented failure output")
    assert len(error_lines) == 1
    assert "result[error]>" in error_lines[0]

    success_lines = _lines_containing(output, "invented success output")
    assert len(success_lines) == 1
    assert "result>" in success_lines[0]
    assert "result[error]>" not in success_lines[0]


